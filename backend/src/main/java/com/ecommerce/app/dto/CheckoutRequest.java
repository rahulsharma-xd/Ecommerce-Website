package com.ecommerce.app.dto;

/**
 * Request DTO for checkout process.
 * Contains credit card information for payment processing (not stored in database).
 */
public class CheckoutRequest {

    private String cardNumber;
    private String cardHolderName;
    private String expiryDate;  // Format: MM/YY
    private String cvv;

    // Constructors
    public CheckoutRequest() {
    }

    public CheckoutRequest(String cardNumber, String cardHolderName, String expiryDate, String cvv) {
        this.cardNumber = cardNumber;
        this.cardHolderName = cardHolderName;
        this.expiryDate = expiryDate;
        this.cvv = cvv;
    }

    // Getters and Setters
    public String getCardNumber() {
        return cardNumber;
    }

    public void setCardNumber(String cardNumber) {
        this.cardNumber = cardNumber;
    }

    public String getCardHolderName() {
        return cardHolderName;
    }

    public void setCardHolderName(String cardHolderName) {
        this.cardHolderName = cardHolderName;
    }

    public String getExpiryDate() {
        return expiryDate;
    }

    public void setExpiryDate(String expiryDate) {
        this.expiryDate = expiryDate;
    }

    public String getCvv() {
        return cvv;
    }

    public void setCvv(String cvv) {
        this.cvv = cvv;
    }
}
